import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';

const sql = readFileSync(
  new URL('../../supabase/migrations/20261121170000_rh_departure_account_lifecycle_reference.sql', import.meta.url),
  'utf8',
);
const panel = readFileSync(
  new URL('../../src/components/hr/DepartureCasesPanel.tsx', import.meta.url),
  'utf8',
);

test('one immutable BIB departure reference per case, generated by the database', () => {
  assert.match(sql, /CREATE SEQUENCE IF NOT EXISTS public\.rh_departure_register_reference_seq/);
  assert.match(sql, /'BIB-RH-DEP-'/);
  assert.match(sql, /BEFORE INSERT OR UPDATE OF employee_id, departure_reference, onboarding_request_id/);
  assert.match(sql, /rh_departure_account_origin_immutable/);
  assert.match(sql, /uq_rh_departure_register_reference/);
});

test('onboarding origin is linked by account UUID, not email or user-provided URL', () => {
  assert.match(sql, /r\.created_user_id = NEW\.employee_id/);
  assert.match(sql, /r\.created_user_id = c\.employee_id/);
  assert.match(sql, /r\.request_kind = 'onboarding'/);
  assert.match(sql, /r\.document_register_reference/);
  assert.doesNotMatch(sql, /r\.work_email\s*=|r\.personal_email\s*=|google\.com|drive\.google/);
});

test('departure listing stays portfolio scoped, read-only, and never closes an account', () => {
  assert.match(sql, /public\.is_canonical_bib_ceo\(actor\)/);
  assert.match(sql, /portfolio\.owner_id = actor/);
  assert.match(sql, /m\.entity_id = c\.employee_id AND m\.ended_at IS NULL/);
  assert.match(sql, /WHERE t\.case_id = c\.id AND t\.state = 'pending'/);
  assert.match(sql, /REVOKE ALL ON FUNCTION public\.rh_departure_lifecycle_list/);
  assert.doesNotMatch(sql, /UPDATE public\.profiles|DELETE FROM auth\.users|UPDATE auth\.users/);
  assert.match(panel, /rh_departure_lifecycle_list/);
  assert.match(panel, /Dossier de départ/);
  assert.match(panel, /Dossier d’entrée/);
  assert.match(panel, /Le compte n’est pas déclaré clôturé/);
});
